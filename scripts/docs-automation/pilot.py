"""Collect a merged PR, review its docs, or publish a validated patch."""
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path("repo")
RUN = Path(".docs-run")
CONFIG = json.loads((HERE / "config.json").read_text())


def require(condition, message):
    if not condition:
        raise ValueError(message)


def cmd(*args, cwd=REPO, **options):
    return subprocess.check_output(args, cwd=cwd, **options).decode()


def api(endpoint, body=None):
    args = ["-X", "POST", "--input", "-"] if body is not None else []
    return json.loads(cmd("gh", "api", endpoint, *args, input=json.dumps(body).encode() if args else None))


def save(name, value):
    (RUN / name).write_text(json.dumps(value, indent=2) + "\n")


def load(name):
    return json.loads((RUN / name).read_text())


def append(variable, text):
    with Path(os.environ[variable]).open("a") as output:
        print(text, file=output)


def checked_path(name):
    parts = name.split("/")
    require(re.fullmatch(r"[\w./-]+", name, re.ASCII) and not {"", ".", ".."}.intersection(parts), f"Invalid path: {name}")
    path = REPO / name
    require(path.resolve() == REPO.resolve() / name, f"Symlink in {name}")
    return path


def doc_path(name):
    path = checked_path(name)
    if re.fullmatch(r"packages/docs/assets/fhir/resources/[a-z0-9-]+\.md", name):
        return path
    prefix = "packages/docs/content/docs/"
    require(name.startswith(prefix) and name.endswith(".md"), f"Outside hand-written docs: {name}")
    page = name[len(prefix):]
    require(not re.match(r"(sdk|decision-guides)[/.]", page), f"Generated page: {name}")
    if re.match(r"api/fhir/(resources|datatypes|medplum)[/.]", page):
        require(re.fullmatch(r"api/fhir/(resources|datatypes|medplum)/_index\.md", page), f"Generated FHIR page: {name}")
    return path


def capture(pages, partial):
    status = cmd("git", "status", "--porcelain", "--no-renames", "--untracked-files=all", "-z")
    changed = {entry[3:] for entry in status.split("\0") if entry}
    require(changed <= set(pages) and (partial or changed == set(pages)), "Edits do not match the plan")
    total = 0
    for name in changed:
        path = doc_path(name)
        total += path.stat().st_size
        require(path.is_file() and not path.stat().st_mode & 0o111 and total <= CONFIG["maxDraftBytes"], f"Invalid file: {name}")
        content = path.read_text()
        require(not re.search(r"\0|<\s*(script|iframe)\b", content, re.I), f"Unsupported content: {name}")
        if name.startswith("packages/docs/content/"):
            header = re.match(r"\A---\n(.*?)^---$", content, re.M | re.S)
            require(header and re.search(r"^title:[ \t]*\S", header[1], re.M), f"Missing front matter: {name}")
    if not changed:
        return ""
    cmd("git", "add", "--", *sorted(changed))
    cmd("git", "diff", "--cached", "--check")
    return cmd("git", "diff", "--cached", "--no-ext-diff", "--no-textconv")


def source(number, repository):
    endpoint = f"repos/{repository}/pulls/{number}"
    pr = api(endpoint)
    require(pr["merged"] and pr["base"]["ref"] == os.environ["BASE_BRANCH"], "Select a merged default-branch PR")
    base = cmd("git", "rev-parse", "HEAD").strip()
    assignee = pr["user"]["login"] if pr["user"]["type"] == "User" else CONFIG["fallbackAssignee"]
    RUN.mkdir()
    save("context.json", dict(number=number, base=base, assignee=assignee, title=pr["title"],
                              body=(pr["body"] or "")[:12000], models=CONFIG["models"], effort=CONFIG["effort"]))
    append("GITHUB_OUTPUT", f"base={base}")
    append("GITHUB_STEP_SUMMARY", f"### Source #{number} at `{base}`\n")

    def stop(outcome, reason):
        questions = [reason] if outcome == "needs-human" else []
        save("classification.json", dict(outcome=outcome, summary=reason, questions=questions, pages=[], evidence=[]))

    if pr["head"]["ref"].startswith("docs/automated-pr-"):
        return stop("no-docs", "This PR was generated by the docs pilot.")
    if pr["changed_files"] > CONFIG["maxSourceFiles"]:
        return stop("needs-human", "PR exceeds the source file limit.")
    sha = pr["merge_commit_sha"]
    require(re.fullmatch("[a-f0-9]{40}", sha), "Invalid landed revision")
    cmd("git", "merge-base", "--is-ancestor", sha, base)
    parents = cmd("git", "rev-list", "--parents", "-n1", sha).split()[1:]
    if not parents or (len(parents) > 1 and parents[1:] != [pr["head"]["sha"]]):
        return stop("needs-human", "Review the merge history to isolate this PR.")
    parent = parents[0]
    files = set(cmd("git", "diff", "--name-only", "--no-renames", "-z", parent, sha).split("\0")) - {""}
    if len(parents) == 1:
        listed = api(endpoint + "/files?per_page=100")
        expected = {f[key] for f in listed for key in ("filename", "previous_filename") if key in f}
        prior = api(f"repos/{repository}/commits/{parent}/pulls?per_page=100")
        complete = len(listed) == pr["changed_files"] and expected == files
        if not complete or len(prior) == 100 or any(p["number"] == number for p in prior):
            return stop("needs-human", "The landed commit could not be isolated as the complete PR.")
    if not 0 < len(files) <= CONFIG["maxSourceFiles"]:
        return stop("needs-human", "Review the landed file set.")
    with tempfile.TemporaryFile() as patch:
        subprocess.run(["git", "diff", "--no-ext-diff", "--no-textconv", parent, sha], cwd=REPO, stdout=patch, check=True)
        if patch.tell() > CONFIG["maxDiffBytes"]:
            return stop("needs-human", "The landed diff exceeds the pilot size limit.")
        patch.seek(0)
        (RUN / "source.diff").write_bytes(patch.read())


def comment(number, repository, text):
    issue = f"repos/{repository}/issues/{number}"
    marker = f"<!-- docs-automation: {repository}#{number} -->"
    query = f'.[] | select(.user.login == "github-actions[bot]" and (.body | startswith("{marker}"))) | .id'
    previous = cmd("gh", "api", "--paginate", issue + "/comments?per_page=100", "--jq", query).strip().splitlines()
    endpoint = f"repos/{repository}/issues/comments/{previous[0]}" if previous else issue + "/comments"
    cmd("gh", "api", "--silent", "-X", "PATCH" if previous else "POST", endpoint, "-f", f"body={marker}\n{text}")


def publish(number, repository):
    context = load("context.json")
    require(os.environ["MODE"] == "open-pr" and context["number"] == number, "Invalid publication request")
    require(cmd("git", "rev-parse", "HEAD").strip() == context["base"], "Wrong docs revision")
    run = f"https://github.com/{repository}/actions/runs/{os.environ['GITHUB_RUN_ID']}"
    report = (RUN / "review.md").read_text() + f"\n[Workflow run]({run})"
    build, action = os.environ["BUILD"], os.environ["NEXT"]
    if build == "failure" or action == "comment":
        reason = "Dependency installation or the docs build failed.\n\n" if build == "failure" else ""
        return comment(number, repository, reason + report)
    require(action == "pr" and build == "success", "A docs PR requires a successful review and build")
    branch = f"docs/automated-pr-{number}"
    existing = api(f"repos/{repository}/pulls?state=all&head={repository.split('/')[0]}:{branch}")
    if existing:
        return comment(number, repository, "Existing documentation PR: " + existing[0]["html_url"])
    plan, draft, verification = load("classification.json"), load("draft.json"), load("verification.json")
    require(plan["outcome"] == "update-docs" and 0 < len(plan["pages"]) <= CONFIG["maxDraftFiles"], "Invalid plan")
    require(not cmd("git", "status", "--porcelain"), "Publication needs a clean checkout")
    cmd("git", "apply", "--index", (RUN / "docs.patch").resolve())
    require(capture(plan["pages"], bool(draft["questions"])), "Empty patch")
    ref = f"refs/heads/{branch}"
    if cmd("git", "ls-remote", "--heads", "origin", ref):
        cmd("git", "fetch", "origin", ref)
        require(cmd("git", "write-tree") == cmd("git", "rev-parse", "FETCH_HEAD^{tree}"), "Existing branch has different edits")
    else:
        cmd("git", "-c", "user.name=github-actions[bot]", "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
            "commit", "--signoff", "-m", f"docs: follow up on #{number}")
        cmd("git", "push", "origin", f"HEAD:{ref}")
    title = f"docs: follow up on #{number}" + (" (needs input)" if draft["questions"] or verification["findings"] else "")
    pr = api(f"repos/{repository}/pulls", dict(head=branch, base=os.environ["BASE_BRANCH"], draft=True, title=title,
                                               body=f"Documentation follow-up for #{number}.\n\n{report}"))
    append("GITHUB_STEP_SUMMARY", pr["html_url"])
    comment(number, repository, "Documentation follow-up: " + pr["html_url"])
    assignee = context["assignee"]
    require(re.fullmatch(r"[\w-]+", assignee), f"Assign a human reviewer to {pr['html_url']}")
    updated = api(f"repos/{repository}/issues/{pr['number']}/assignees", {"assignees": [assignee]})
    require(any(a["login"] == assignee for a in updated["assignees"]), f"Assign {assignee} to {pr['html_url']}")


if __name__ == "__main__":
    number, repository = os.environ["PR_NUMBER"], os.environ["GITHUB_REPOSITORY"]
    require(re.fullmatch(r"[1-9][0-9]{0,8}", number) and re.fullmatch(r"[\w.-]+/[\w.-]+", repository), "Invalid source PR")
    require(os.environ["MODE"] in ("classify", "draft", "open-pr"), "Invalid pilot mode")
    {"source": source, "publish": publish}[sys.argv[1]](int(number), repository)
