/* global console */
/* global process */

import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

function copyDir(sourceDir, targetDir) {
  const files = readdirSync(sourceDir, { withFileTypes: true });
  mkdirSync(targetDir, { recursive: true });

  for (const file of files) {
    const sourceFilePath = join(sourceDir, file.name);
    const targetFilePath = join(targetDir, file.name);
    if (file.isDirectory()) {
      copyDir(sourceFilePath, targetFilePath);
    } else {
      copyFile(sourceFilePath, targetFilePath);
    }
  }
}

function copyFile(sourceFile, targetFile) {
  if (sourceFile.endsWith('.md')) {
    writeFileSync(targetFile.replace('.md', '.mdx'), escapeMdx(sourceFile, readFileSync(sourceFile, 'utf8')));
  } else {
    copyFileSync(sourceFile, targetFile);
  }
}

// HTML tags that API Documenter legitimately emits (e.g. the parameter tables).
// Any other `<Identifier>` in prose is almost always a TypeScript type reference
// such as `CodeableReference<HealthcareService>` from a JSDoc comment. MDX parses
// those as (unclosed) JSX tags and fails the build, so we escape them to literal
// text while leaving real HTML markup intact.
const ALLOWED_HTML_TAGS = new Set([
  'a',
  'abbr',
  'b',
  'blockquote',
  'br',
  'caption',
  'cite',
  'code',
  'col',
  'colgroup',
  'dd',
  'del',
  'dfn',
  'div',
  'dl',
  'dt',
  'em',
  'figcaption',
  'figure',
  'h1',
  'h2',
  'h3',
  'h4',
  'h5',
  'h6',
  'hr',
  'i',
  'img',
  'ins',
  'kbd',
  'li',
  'mark',
  'ol',
  'p',
  'pre',
  'q',
  's',
  'samp',
  'small',
  'span',
  'strong',
  'sub',
  'sup',
  'table',
  'tbody',
  'td',
  'th',
  'thead',
  'tr',
  'u',
  'ul',
  'var',
]);

// Whether the `<` at index `i` begins a token that is NOT a known HTML tag (and so
// should be escaped to `&lt;` to keep MDX from treating it as JSX).
function shouldEscapeAngleBracket(text, i) {
  const match = /^<\/?([A-Za-z][A-Za-z0-9-]*)/.exec(text.slice(i));
  if (!match) {
    // Not a tag-like token (e.g. `a < b`); leave it untouched.
    return false;
  }
  return !ALLOWED_HTML_TAGS.has(match[1].toLowerCase());
}

function escapeMdx(fileName, text) {
  text = text
    .replace('<!-- Do not edit this file. It is automatically generated by API Documenter. -->', '')
    .trimStart()
    .replaceAll('.md)', ')')
    .replaceAll('<!-- -->\\[\\]', '')
    .replaceAll('<!-- -->', '');

  if (basename(fileName) === 'index.md') {
    // In Docusaurus, the index.mdx file is used as the landing page for the folder.
    // Relative links are relative to the parent, not the index.mdx file.
    text = text.replaceAll('](./index)', '](../)').replaceAll('](./', '](./sdk/');
  } else {
    text = text.replaceAll('[Home](./index)', '[Home](./)');
  }

  // Escape { and } characters outside of code blocks
  const specialChars = ['{', '}'];
  let inSingleBacktick = false;
  let inTripleBacktick = false;
  let backtickCount = 0;
  let result = '';

  for (let i = 0; i < text.length; i++) {
    const char = text[i];

    // Check for backtick
    if (char === '`') {
      result += char;
      backtickCount++;

      if (backtickCount === 3) {
        inTripleBacktick = !inTripleBacktick;
        backtickCount = 0;
      } else if (backtickCount === 1 && i < text.length - 1 && text[i + 1] !== '`') {
        inSingleBacktick = !inSingleBacktick;
        backtickCount = 0;
      }
    } else {
      if (backtickCount > 0 && backtickCount < 3) {
        // Add missed backticks to result
        result += '`'.repeat(backtickCount);
        backtickCount = 0;
      }

      if (!inSingleBacktick && !inTripleBacktick && char === '<' && shouldEscapeAngleBracket(text, i)) {
        // Escape a non-HTML `<Type>` token so MDX treats it as literal text
        result += '&lt;';
      } else if (!inSingleBacktick && !inTripleBacktick && specialChars.includes(char)) {
        // Escape character if not in backtick block
        result += '\\' + char;
      } else {
        // Add character as is
        result += char;
      }
    }
  }

  // Append any remaining backticks
  if (backtickCount > 0) {
    result += '`'.repeat(backtickCount);
  }

  return result;
}

if (import.meta.main) {
  if (process.argv.length < 4) {
    console.log('Usage: node markdown-to-mdx.mjs <sourceDir> <targetDir>');
    process.exit(1);
  }
  const [_node, _script, source, target] = process.argv;
  try {
    copyDir(source, target);
  } catch (error) {
    console.error('Error processing files:', error);
  }
}
