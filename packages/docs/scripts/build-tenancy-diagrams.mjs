const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../static/img/tenancy-design');
// Match the standard Mermaid resource diagrams used in Care Coordination and Messaging.
const theme = { fill: '#ECECFF', border: '#9370DB', text: '#333', canvas: '#f6f7f8' };
const esc = (s) => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');

class Diagram {
  constructor(name, height, title, description) {
    this.name = name;
    this.height = height;
    this.title = title;
    this.description = description;
    this.parts = [];
  }
  rect(x, y, w, h, fill = '#fff', stroke = '#aaa', radius = 0, dash = false, shadow = false) {
    this.parts.push(
      `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}" fill="${fill}" stroke="${stroke}" stroke-width="1"${shadow ? ' filter="url(#resource-shadow)"' : ''}${dash ? ' stroke-dasharray="6 5"' : ''}/>`
    );
  }
  text(x, y, text, size = 17, weight = 400, anchor = 'start', color = theme.text) {
    this.parts.push(`<text x="${x}" y="${y}" font-size="${size}" font-weight="${weight}" text-anchor="${anchor}" fill="${color}">${esc(text)}</text>`);
  }
  lines(x, y, lines, size = 17, weight = 400, anchor = 'start', color) {
    lines.forEach((s, i) => this.text(x, y + i * 23, s, size, weight, anchor, color));
  }
  group(x, y, w, h, label) {
    this.rect(x, y, w, h, '#ffffde', '#aaaa33');
    this.text(x + 16, y + 28, label, 16, 400);
  }
  resource(x, y, w, type, detail = '') {
    this.rect(x, y, w, 70, theme.fill, theme.border, 0, false, true);
    this.text(x + w / 2, y + 28, type, 16, 400, 'middle');
    if (detail) this.text(x + w / 2, y + 52, detail, 15, 400, 'middle', '#555');
  }
  pill(x, y, w, title, detail = '') {
    this.rect(x, y, w, detail ? 66 : 44, theme.fill, theme.border, 5, false, true);
    this.text(x + w / 2, y + 28, title, 16, 400, 'middle');
    if (detail) this.text(x + w / 2, y + 51, detail, 15, 400, 'middle');
  }
  arrow(points, label, lx, ly, dashed = false) {
    const d = points.map(([x, y], i) => `${i ? 'L' : 'M'}${x},${y}`).join(' ');
    this.parts.push(`<path d="${d}" fill="none" stroke="#333" stroke-width="1.2"${dashed ? ' stroke-dasharray="6 5"' : ''} marker-end="url(#arrow)"/>`);
    if (label) {
      const width = label.length * 7.2 + 12;
      this.parts.push(`<rect x="${lx - width / 2}" y="${ly - 15}" width="${width}" height="20" fill="#e8e8e8" rx="0"/>`);
      this.text(lx, ly, label, 14, 400, 'middle', theme.text);
    }
  }
  save() {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="760" height="${this.height}" viewBox="0 0 760 ${this.height}" role="img" aria-labelledby="title desc">
<title id="title">${esc(this.title)}</title><desc id="desc">${esc(this.description)}</desc>
<!-- Generated by packages/docs/scripts/build-tenancy-diagrams.mjs -->
<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 Z" fill="#333"/></marker><filter id="resource-shadow" x="-10%" y="-15%" width="125%" height="140%"><feDropShadow dx="1" dy="2" stdDeviation="1" flood-color="#b9b9b9" flood-opacity="0.7"/></filter></defs>
<rect width="760" height="${this.height}" fill="${theme.canvas}"/>
<g font-family="trebuchet ms, verdana, arial, sans-serif">${this.parts.join('\n')}</g></svg>\n`;
    fs.writeFileSync(path.join(outDir, `${this.name}.svg`), svg);
  }
}

